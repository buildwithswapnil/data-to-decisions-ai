import sqlite3
import os

# WHY: We define the database path here so the tool always knows 
# exactly where the 'healthcare_data.db' file is located on your disk.
DB_PATH = os.path.join(os.path.dirname(__file__), '..', 'db', 'healthcare_data.db')

def execute_query(sql_query: str):
    """
    WHY: This function is the bridge. It takes a raw string of SQL 
    (generated by the AI) and actually runs it against our database.
    """
    try:
        # WHY: We establish a connection to the database. 
        # Think of this as opening the 'vault' to read the data.
        conn = sqlite3.connect(DB_PATH)
        cursor = conn.cursor()
        
        # WHY: We execute the query provided by the agent.
        cursor.execute(sql_query)
        
        # WHY: We fetch all matching rows. 
        # If the query is 'SELECT * FROM patients', this catches the list of patients.
        results = cursor.fetchall()
        
        # WHY: Always close the connection to prevent memory leaks 
        # and keep the database 'unlocked' for other agents to use.
        conn.close()
        
        return {"status": "success", "data": results}

    except Exception as e:
        # WHY: This is the most CRITICAL part for an AI Agent.
        # If the AI writes bad SQL, we don't want the app to crash.
        # Instead, we catch the error and send the 'Traceback' back to the AI.
        # The AI reads this error and uses it to fix its own code!
        return {"status": "error", "message": str(e)}

# WHY: This block allows us to test the tool manually before 
# we let the AI touch it. It ensures the 'hands' are working.
if __name__ == "__main__":
    test_query = "SELECT * FROM patients;"
    print(f"Testing SQL Engine with query: {test_query}")
    print(execute_query(test_query))